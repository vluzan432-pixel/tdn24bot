async def _references(kind: str, digest: str, extra: str) -> list:
    if kind == "literature":
        task = (
            "Склади список ЛІТЕРАТУРИ та нот, які студент ПРЯМО назвав у даних (автор, назва, місто, "
            "видавництво, рік, кількість сторінок). Формат: «Автор. Назва. Місто : Видавництво, Рік. "
            "Кількість сторінок.» Якщо якихось відомостей бракує — залиши позначку [ДОДАТИ: ...] у цьому "
            "місці. НІЧОГО не вигадуй і не додавай джерел від себе."
        )
    else:
        task = (
            "Склади список ІНФОРМАЦІЙНИХ РЕСУРСІВ (веб-сайти, YouTube), які студент ПРЯМО назвав у даних. "
            "Формат: «Назва ресурсу: веб-сайт. URL: https://... (дата звернення: ДД.ММ.РР р.).» "
            "URL і дати бери лише з даних; якщо немає — [ДОДАТИ: URL] / [ДОДАТИ: дата звернення]. "
            "НІЧОГО не вигадуй."
        )
    system = "Ти — бібліограф. " + task + ' Відповідь — ЛИШЕ JSON-масив рядків; якщо нічого немає — [].'
    prompt = f"ЗАПИСИ ЩОДЕННИКА:\n{digest}\n\nДОДАТКОВІ ДАНІ ВІД СТУДЕНТА:\n{extra or '(немає)'}"
    data = await ai.generate_json(system, prompt, temperature=0.1, max_tokens=3000)
    if isinstance(data, dict):  # інколи модель обгортає масив в об'єкт
        data = next((v for v in data.values() if isinstance(v, list)), [])
    return [str(x).strip() for x in (data or []) if str(x).strip()]


TOTAL_STEPS = len(SECTION_PLAN) + 3  # + s12, література, ресурси


async def generate_report_sections(profile: dict, cfg: dict, entries: list, extra: str, progress=None) -> dict:
    """Генерує розділи ПОСЛІДОВНО (щоб не обрізались токени й не впертись у ліміти).
    progress(step, total, label) — необов'язковий async-колбек для оновлення статусу."""
    digest = diary_digest(entries)
    sections = {}
    step = 0

    async def tick(label):
        nonlocal step
        step += 1
        if progress:
            await progress(step, TOTAL_STEPS, label)
        await asyncio.sleep(1.5)  # невелика пауза, щоб не ловити 429 на безкоштовному ліміті

    for key, instruction, words in SECTION_PLAN:
        await tick(instruction.split(":")[0])
        sections[key] = await _section(key, instruction, words, profile, cfg, digest, extra)
        if key == "s11":
            await tick("РОЗДІЛ І, 1.2 «Аналіз сайтів»")
            sections["s12"] = await _s12(profile, cfg, digest, extra)

    await tick("Список літератури")
    sections["literature"] = await _references("literature", digest, extra)
    await tick("Інформаційні ресурси")
    sections["resources"] = await _references("resources", digest, extra)
    sections["media_links"] = []
    return sections


