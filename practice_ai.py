def grammatical_gender(profile: dict) -> str:
    """Рід дієслів минулого часу за по батькові з ПІБ: …івна/…овна → жіночий, …ович/…івич → чоловічий."""
    parts = (profile.get("full_name") or "").split()
    if len(parts) >= 3:
        patronymic = parts[-1].lower()
        if patronymic.endswith("на"):
            return "жіночий (я виконувала, я опрацювала)"
        if patronymic.endswith("ч"):
            return "чоловічий (я виконував, я опрацював)"
    return ""


