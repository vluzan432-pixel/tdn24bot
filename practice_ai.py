async def _section(key, instruction, words, profile, cfg, digest, extra):
    prompt = (
        f"ПРОФІЛЬ:\n{profile_context(profile, cfg)}\n\n"
        f"ЗАПИСИ ЩОДЕННИКА:\n{digest}\n\n"
        f"ДОДАТКОВІ ДАНІ ВІД СТУДЕНТА:\n{extra or '(немає)'}\n\n"
        f"ЗАВДАННЯ: {instruction}\nОрієнтовний обсяг: {words} слів."
    )
    text = await ai.generate(REPORT_SYSTEM, prompt, long=True, temperature=0.6, max_tokens=6000)
    return text.strip()


