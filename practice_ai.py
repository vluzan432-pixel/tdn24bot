async def analyze_entry(profile: dict, cfg: dict, description: str) -> list:
    """Повертає список із 0–4 навідних запитань (порожній = інформації достатньо)."""
    system = (
        "Ти — помічник студента-музиканта, який веде щоденник практики. "
        "Оціни, чи достатньо інформації в описі дня для змістовного академічного запису. "
        "Якщо недостатньо — сформулюй 2–4 КОРОТКІ конкретні навідні запитання "
        "(напр.: повна офіційна назва колективу; які саме твори розбирали — назви, автори/обробки; "
        "які методичні чи виконавські завдання відпрацьовували; формат — офлайн чи Zoom). "
        "Не питай про те, що вже є в описі чи профілі. "
        'Відповідь — ЛИШЕ JSON: {"enough": true/false, "questions": ["...", "..."]}.'
    )
    prompt = f"ПРОФІЛЬ:\n{profile_context(profile, cfg)}\n\nОПИС ДНЯ ВІД СТУДЕНТА:\n{description}"
    data = await ai.generate_json(system, prompt, temperature=0.3, max_tokens=800)
    if not isinstance(data, dict) or data.get("enough"):
        return []
    questions = [str(q).strip() for q in (data.get("questions") or []) if str(q).strip()]
    return questions[:4]


async def generate_entry(profile: dict, cfg: dict, date_str: str, description: str) -> dict:
    """Повертає {'tasks': str, 'annotation': str}."""
    system = (
        "Ти — помічник студента-музиканта (університет культури і мистецтв), який оформлює "
        "щоденник практики. Сформуй запис із двох полів.\n"
        "1) tasks — «Перелік виконаних завдань та робот»: стисла чітка назва виду роботи + "
        "офіційна назва колективу/події, 1 рядок.\n"
        "2) annotation — «Анотація»: розгорнутий (5–9 речень) змістовний опис у науково-діловому "
        "стилі, що розкриває фахову цінність роботи саме для цього студента з огляду на його "
        "спеціалізацію (вокаліст, диригент/керівник ансамблю, артист хору, інструменталіст, "
        "аранжувальник, організатор заходів). Різноманітні початки речень, без шаблонних "
        "повторів. Якщо в даних є репертуар — наведи його переліком (назва, автор/обробка).\n"
        f"{BASE_RULES}\n{CRITERIA}\n\n{STYLE_EXAMPLES}\n\n"
        'Відповідь — ЛИШЕ JSON: {"tasks": "...", "annotation": "..."}.'
    )
    prompt = (
        f"ПРОФІЛЬ:\n{profile_context(profile, cfg)}\n\nДАТА: {date_str}\n\n"
        f"ЩО РОЗПОВІВ СТУДЕНТ (включно з відповідями на уточнення):\n{description}"
    )
    data = await ai.generate_json(system, prompt, temperature=0.7, max_tokens=2000)
    if not isinstance(data, dict) or not data.get("tasks") or not data.get("annotation"):
        raise ai.AIUnavailable("ШІ повернув неповний запис")
    return {"tasks": str(data["tasks"]).strip(), "annotation": str(data["annotation"]).strip()}


# ------------------------------------------------------------ звіт

def diary_digest(entries: list, max_chars_per_entry: int = 450) -> str:
    lines = []
    for e in sorted(entries, key=lambda x: x["entry_date"]):
        d = e["entry_date"][8:10] + "." + e["entry_date"][5:7] + "." + e["entry_date"][:4]
        ann = e["annotation"].replace("\n", " ")
        if len(ann) > max_chars_per_entry:
            ann = ann[:max_chars_per_entry] + "…"
        lines.append(f"[{d}] {e['tasks']} — {ann}")
    return "\n".join(lines)


def detect_gaps(entries: list, extra: str = "") -> list:
    """Які обов'язкові підрозділи звіту навряд чи можна наповнити даними з записів."""
    text = (diary_digest(entries, 10000) + "\n" + (extra or "")).lower()
    gaps = []
    if not re.search(r"сайт|folk\.|https?://|www\.", text):
        gaps.append("сайти мистецьких установ (розділ 1.2)")
    if not re.search(r"літератур|підручник|посібник|монограф|стат(тя|ті)|книг", text):
        gaps.append("музично-теоретична література (розділ 2.3 і список літератури)")
    return gaps


