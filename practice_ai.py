def profile_context(profile: dict, cfg: dict) -> str:
    parts = [
        f"Вид практики: {profile.get('practice_kind') or cfg.get('practice_kind', '')}",
        f"Спеціальність: {cfg.get('specialty', '')}; ОПП: {cfg.get('program', '')}",
        f"Спеціалізація / ролі студента: {profile.get('specialization') or 'не вказано'}",
        f"База практики: {profile.get('practice_base') or 'не вказано'}",
        f"Основний творчий колектив: {profile.get('collective') or 'не вказано'}",
        f"Терміни практики: {cfg.get('terms') or 'не вказано'}",
    ]
    return "\n".join(parts)


